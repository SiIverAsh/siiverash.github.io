import os
import re
import subprocess
from datetime import date, datetime, timedelta, timezone

import yaml

POSTS_DIR = "_posts"
SERIALS_FILE = os.path.join("_data", "post_serials.yml")
BEIJING = timezone(timedelta(hours=8))
DATE_FORMAT = "%Y-%m-%d %H:%M:%S %z"


def parse_date(value):
    """Accept Jekyll's date forms without changing an explicit publication date."""
    if isinstance(value, datetime):
        parsed = value
    elif isinstance(value, date):
        parsed = datetime.combine(value, datetime.min.time())
    else:
        cleaned = str(value or "").strip()
        if not cleaned or "UPLOAD_TIME" in cleaned:
            return None
        try:
            parsed = datetime.fromisoformat(cleaned.replace("Z", "+00:00"))
        except ValueError:
            # Python 3.9's fromisoformat does not accept Jekyll's compact
            # timezone form ("2026-02-22 20:14:52 +0800").
            for fmt in (DATE_FORMAT, "%Y-%m-%d %H:%M:%S%z", "%Y-%m-%dT%H:%M:%S%z"):
                try:
                    parsed = datetime.strptime(cleaned, fmt)
                    break
                except ValueError:
                    continue
            else:
                return None
    return parsed.replace(tzinfo=BEIJING) if parsed.tzinfo is None else parsed


def parse_sort_key(value, filename):
    parsed = parse_date(value) or parse_date(filename[:10])
    return (parsed.timestamp() if parsed else 0.0, filename)


def write_post_serials(records):
    ordered = sorted(records, key=lambda item: item[0])
    serials = {
        rel_path: f"0x{idx:02X}"
        for idx, (_, rel_path) in enumerate(ordered, start=1)
    }
    os.makedirs(os.path.dirname(SERIALS_FILE), exist_ok=True)
    with open(SERIALS_FILE, "w", encoding="utf-8") as handle:
        handle.write("# Auto-generated by scripts/blog_lifecycle_manager.py\n")
        yaml.safe_dump(serials, handle, allow_unicode=True, sort_keys=False)
    print(f"🔢 [序号生成] 已更新 {SERIALS_FILE}（共 {len(serials)} 篇）", flush=True)


def get_beijing_time():
    return datetime.now(BEIJING)


def git_output(*arguments):
    try:
        return subprocess.check_output(
            ["git", *arguments], encoding="utf-8", stderr=subprocess.DEVNULL
        )
    except (subprocess.CalledProcessError, OSError):
        return None


def split_post(content):
    # Match delimiters on their own lines; '---' inside a title is ordinary YAML.
    match = re.match(r"\A---[ \t]*\r?\n(.*?)^---[ \t]*(?:\r?\n|$)", content, re.S | re.M)
    if not match:
        return None
    try:
        front_matter = yaml.safe_load(match.group(1))
    except yaml.YAMLError:
        return None
    if not isinstance(front_matter, dict):
        return None
    return front_matter, content[match.end():]


def get_git_post(filepath, ref):
    content = git_output("show", f"{ref}:{filepath.replace(os.sep, '/')}")
    return split_post(content) if content is not None else None


def normalized_body(post):
    return post[1].replace("\r\n", "\n").strip() if post else None


def is_ancestor(older, newer="HEAD"):
    return git_output("merge-base", "--is-ancestor", older, newer) is not None


def comparison_base():
    """Include changes since the last completed automation, even after a failed push."""
    bases = []
    before = os.getenv("POST_BASE_SHA", "").strip()
    if re.fullmatch(r"[0-9a-fA-F]{40,64}", before) and set(before) != {"0"}:
        if is_ancestor(before):
            bases.append(before)
    checkpoint = git_output(
        "log", "-1", "--format=%H", "--grep=^Automated: Blog Automation", "HEAD"
    )
    if checkpoint and is_ancestor(checkpoint.strip()):
        bases.append(checkpoint.strip())
    if bases:
        # The older boundary also catches changes left pending by a previous run.
        oldest = bases[0]
        for candidate in bases[1:]:
            if is_ancestor(candidate, oldest):
                oldest = candidate
        return oldest
    # An initial manual run has no push boundary/checkpoint. Inspect only HEAD's
    # change instead of backfilling metadata throughout an existing archive.
    parent = git_output("rev-parse", "--verify", "HEAD^1")
    return parent.strip() if parent else None


def post_history(filepath):
    """Read versions with their commit dates, following slug/file renames."""
    log = git_output(
        "log", "--follow", "--diff-merges=first-parent",
        "--format=%x1e%H%x00%cI", "--name-status", "-z", "--", filepath
    )
    history = []
    for record in (log or "").split("\x1e"):
        fields = record.split("\x00")
        if len(fields) < 4:
            continue
        sha, committed_at, status = fields[0], parse_date(fields[1]), fields[2].strip()
        path_index = 4 if status.startswith(("R", "C")) else 3
        if len(fields) <= path_index or not committed_at:
            continue
        path = fields[path_index]
        post = get_git_post(path, sha)
        if post:
            history.append((sha, committed_at, path, post))
    return history


def post_at_base(filepath, base, history):
    if not base:
        return None
    post = get_git_post(filepath, base)
    if post:
        return post
    # A rename must retain the old publication date and compare the old body.
    for path in dict.fromkeys(entry[2] for entry in history):
        if path != filepath:
            post = get_git_post(path, base)
            if post:
                return post
    return None


def latest_body_change(history, body=None):
    if not history:
        return None
    if body is None:
        body = normalized_body(history[0][3])
    paths = list(dict.fromkeys(entry[2] for entry in history))
    source_refs = ["HEAD"]
    for sha, committed_at, path, post in history:
        if normalized_body(post) != body or not any(is_ancestor(sha, ref) for ref in source_refs):
            continue
        parents = git_output("rev-list", "--parents", "-n", "1", sha)
        inherited_from = []
        for parent in (parents or "").split()[1:]:
            parent_post = get_git_post(path, parent)
            # A rename may inherit the same body under the previous filename.
            if parent_post is None:
                for old_path in paths:
                    parent_post = get_git_post(old_path, parent)
                    if parent_post:
                        break
            if normalized_body(parent_post) == body:
                inherited_from.append(parent)
        # Metadata-only commits and ordinary merges inherit a parent's body.
        # A conflict resolution with a new body differs from every parent.
        if not inherited_from:
            return committed_at
        # Follow only the matching parents, excluding coincidentally identical
        # text introduced and later discarded on an unrelated sibling branch.
        source_refs = inherited_from
    return None


def process_lifecycle():
    base = comparison_base()
    serial_records = []
    filenames = sorted(os.listdir(POSTS_DIR)) if os.path.isdir(POSTS_DIR) else []

    for filename in filenames:
        if not filename.endswith(".md") or filename == "BLOG_TEMPLATE.md":
            continue
        filepath = os.path.join(POSTS_DIR, filename)
        with open(filepath, "r", encoding="utf-8") as handle:
            post = split_post(handle.read())
        if not post:
            continue
        front_matter, body = post
        history = post_history(filepath)
        needs_update = False
        publication_date = parse_date(front_matter.get("date"))

        if publication_date is None:
            # Git dates survive reruns and multi-commit pushes. A local untracked
            # draft falls back to its filename date, then to the current time.
            publication_date = (
                history[-1][1] if history else parse_date(filename[:10]) or get_beijing_time()
            )
            front_matter["date"] = publication_date.astimezone(BEIJING).strftime(DATE_FORMAT)
            needs_update = True
            print(f"🆕 [发布初始化] {filename}（使用稳定的来源日期）", flush=True)

        base_post = post_at_base(filepath, base, history)
        committed_post = get_git_post(filepath, "HEAD")
        changed_at = None
        if committed_post and normalized_body(post) != normalized_body(committed_post):
            # Only an uncommitted local edit lacks a commit timestamp.
            changed_at = get_beijing_time()
        elif base_post and normalized_body(post) != normalized_body(base_post):
            changed_at = latest_body_change(history, normalized_body(post))

        modified_at = parse_date(front_matter.get("last_modified_at"))
        if changed_at and changed_at > publication_date and (not modified_at or changed_at > modified_at):
            front_matter["last_modified_at"] = changed_at.astimezone(BEIJING).strftime(DATE_FORMAT)
            needs_update = True
            print(f"📝 [正文内容更新] {filename}（使用正文修改时间）", flush=True)

        if needs_update:
            fm_yaml = yaml.safe_dump(front_matter, allow_unicode=True, sort_keys=False).strip()
            with open(filepath, "w", encoding="utf-8") as handle:
                handle.write(f"---\n{fm_yaml}\n---\n{body}")

        serial_records.append((parse_sort_key(front_matter.get("date"), filename), filepath.replace(os.sep, "/")))

    # Keep the generated map available even when the last post was deleted.
    write_post_serials(serial_records)


if __name__ == "__main__":
    process_lifecycle()
